def update_ruku_file(file_path: Path, translations: dict, mufradat_markdown: str):
    content = file_path.read_text(encoding="utf-8")

    # 1. Update translations table in Section 1
    # Match pattern: | **X** | ... | (আয়াত X-এর প্রামাণ্য বঙ্গানুবাদ) |
    for a_num, trans in translations.items():
        # Bengali digit
        bn_num = "".join("০১২৩৪৫৬৭৮৯"[int(d)] for d in str(a_num))
        # Replace either ascii or bengali digit in placeholder
        pattern = rf"(\| \*\*(?:{a_num}|{bn_num})\*\* \| [^|]+ \|)\s*\(আয়াত [০-৯\d]+-এর প্রামাণ্য বঙ্গানুবাদ\)\s*\|"
        replacement = rf"\g<1> {trans} |"
        content = re.sub(pattern, replacement, content)

    # 2. Update Section 2 Mufradat table
    # Replace everything between ## ২. লুগাভী ও সরফী তাহকীক এবং মুফরাদাতুল কুরআন and ## ৩. ই'রাব
    sec2_pattern = r"(## ২\. লুগাভী ও সরফী তাহকীক এবং মুফরাদাতুল কুরআন\s*\n\n)([\s\S]*?)(\n\n---|\n\n## ৩\.)"
    sec2_replacement = rf"\g<1>{mufradat_markdown}\g<3>"
    content = re.sub(sec2_pattern, sec2_replacement, content)

    file_path.write_text(content, encoding="utf-8")
    print(f"Updated {file_path.name}")


