def replace_section(text, sec_no, new_body, next_sec_no):
    # replace from '## <sec_no>.' up to (excluding) '## <next_sec_no>.'
    pat = re.compile(r"(?ms)^##\s*" + sec_no + r"\..*?(?=^##\s*" + next_sec_no + r"\.)")
    if not pat.search(text):
        raise RuntimeError(f"section {sec_no} not found")
    return pat.sub(new_body.rstrip() + "\n\n", text, count=1)

