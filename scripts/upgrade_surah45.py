from audit_ruku import audit_file

BENGALI_DIGITS = "০১২৩৪৫৬৭৮৯"
def to_bn(n: int) -> str:
    return "".join(BENGALI_DIGITS[int(c)] for c in str(n))

def to_bn_pad(n: int) -> str:
    return "".join(BENGALI_DIGITS[int(c)] for c in f"{n:02d}")

def update_ruku(fpath: Path, trans: dict, mufradat_table: str, irab_text: str = None):
    content = fpath.read_text(encoding='utf-8')
    for a_num, t_text in trans.items():
        bn_num = to_bn(int(a_num))
        old_pat = rf'\|\s*\*\*{bn_num}\*\*\s*\|\s*(﴿[^﴾]+﴾)\s*\|\s*\(আয়াত {bn_num}-এর প্রামাণ্য বঙ্গানুবাদ\)\s*\|'
        new_sub = rf'| **{bn_num}** | \1 | {t_text} |'
        content = re.sub(old_pat, new_sub, content)

    # Replace mufradat table
    sec2_pat = r'## ২\. লুগাভী ও সরফী তাহকীক এবং মুফরাদাতুল কুরআন[\s\S]*?(?=---\s*\n\s*## ৩\.)'
    content = re.sub(sec2_pat, f"## ২. লুগাভী ও সরফী তাহকীক এবং মুফরাদাতুল কুরআন\n\n{mufradat_table.strip()}\n\n", content)

    # Replace I'rab stub if present and provided
    if irab_text and "প্রযোজ্য নয় — এই রুকুর আয়াতসমূহের" in content:
        sec3_pat = r'## ৩\. ই\'রাব ও নাহবী বিশ্লেষণ\s+প্রযোজ্য নয় — এই রুকুর আয়াতসমূহের মৌলিক বাক্যগঠন সুস্পষ্ট; কোনো মতভেদপূর্ণ বা অস্পষ্ট নাহবী জটিলতা নেই।'
        content = re.sub(sec3_pat, f"## ৩. ই'রাব ও নাহবী বিশ্লেষণ\n\n{irab_text.strip()}", content)

    fpath.write_text(content, encoding='utf-8')
    ok, errs, warns = audit_file(fpath, json_report=True)
    if not ok:
        print(f"FAILED on {fpath.name}: {errs}")
    else:
        print(f"PASSED on {fpath.name}")
    return ok

