## ১১. আধুনিক নাস্তিক্যবাদী ও প্রাচ্যবিদদের সংশয় নিরসন

### সংশয় ১: "আমরা তো অনেক দু‘আ করি কিন্তু সব দু‘আ তো কবুল হয় না, তবে আয়াত ৬০-এ 'আমি সাড়া দেব' কেন বলা হলো?"
